export function gatewayText(key: CopyKey) {
  return copy[key][getActiveLocale() === "zh" ? 0 : 1];
}
export function useCopy() {
  const { locale } = useLanguage();
  return (key: CopyKey) => copy[key][locale === "zh" ? 0 : 1];
}
